/**
 * Prep step: prepares the ClimWeb Weather App in .climweb with this country's
 * settings, ready to preview or build.
 *
 *   1. Validate the settings, stopping on errors so a broken config never
 *      reaches the app
 *   2. Fetch the app source into .climweb (a fresh clone, or an existing
 *      checkout reset to the latest commit, keeping node_modules). A ref
 *      fetched less than 5 hours ago is reused without fetching again
 *   3. Write .env from the app's .env.example and country.json
 *   4. Update app.json with the app's identity, icons and store links
 *   5. Copy in weather symbols, warning icons, branding and place data
 *   6. Install the configured languages
 *   7. Install dependencies and check them against the app's Expo SDK
 *   8. Keep the ios/ and android/ projects from the last expo run if nothing
 *      they're generated from has changed, so pod install isn't repeated
 *
 * Alert feed settings come from the default language (english.json) until the
 * app supports a CAP feed per language.
 */

import { createHash } from 'crypto';
import { execFileSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { styleText } from 'util';
import { validate } from '../validate';
import { age, isFresh } from './cache';

const APP_REPO = 'https://github.com/wmo-raf/climweb-weather-app.git';
export const APP_DIR = '.climweb';
const DEFAULT_REF = 'main';

const LANGUAGES_DIR = 'languages';
const DEFAULT_LANGUAGE_FILE = 'english.json';

// Where this repository's files go in the app
const TARGETS = {
  symbols: 'assets/weather_icon/png',
  warnings: 'assets',
  branding: {
    icon: 'assets/icon.png',
    adaptive_icon_foreground: 'assets/adaptive-icon.png',
    splash_image: 'assets/splash.png',
  },
  cities: 'assets/cities.json',
  geonames: { from: 'data/geo/geonames.json', to: 'assets/geonames.json' },
  autocomplete: { from: ['data/geo/dataset.json', 'data/geo/trie.json'], to: 'lib/autocomplete' },
  translations: 'lib/localization/translations',
} as const;

// Records which package-lock.json node_modules was installed from
const INSTALL_MARKER = 'node_modules/.prep-lock-hash';
// Records which ref was last fetched and when, inside .git so git clean keeps it
const FETCH_MARKER = 'climweb-prep-fetch.json';
// Fingerprint the native projects were last generated from, also inside .git
const NATIVE_MARKER = 'climweb-prep-native.json';
// Generated by expo run (ignored by the app's git), kept between runs
const NATIVE_DIRS = ['ios', 'android'];
// Expo's local state, also ignored by the app's git. expo run:ios only skips
// pod install if .expo/prebuild/cached-packages.json is still there and matches
// package.json, so it has to survive with the native projects.
const EXPO_STATE_DIR = '.expo';

export interface AppOptions {
  root: string;
  ref?: string;
  skipInstall?: boolean;
  /** Skip step 1 because the caller has already validated the settings */
  validated?: boolean;
  /** Reuse the app fetched in the last few hours and the installed node_modules; false fetches and installs again */
  cache?: boolean;
}

// The parts of country.json and the language files this step reads. Their
// shape is guaranteed by the validation in step 1.
interface Country {
  app: { name: string; ios_bundle_id: string; android_package: string; eas_project_id: string; app_store_url: string; play_store_url: string };
  branding: Record<keyof typeof TARGETS.branding, string> & { adaptive_icon_background_colour: string };
  region: { timezone: string; bbox: number[]; default_cities: string };
  forecast: { provider: string; api_url: string; fallback_api_url: string; user_agent: string };
  alerts: { provider: string };
  defaults: { units: { temperature: string; wind: string; precipitation: string } };
  features: { review_prompt: boolean };
}

interface Language {
  file: string;
  code: string;
  name: string;
  native_name: string;
  cap_feed_url: string;
  fallback_cap_feed_url: string;
  cap_sender_id: string;
  translations: Record<string, string>;
}

// ---------------------------------------------------------------------------
// Helpers

function run(command: string, args: string[], cwd: string, env?: NodeJS.ProcessEnv) {
  execFileSync(command, args, {
    cwd,
    stdio: 'inherit',
    env: { ...process.env, ...env },
    shell: process.platform === 'win32', // npm and npx are .cmd scripts on Windows
  });
}

function capture(command: string, args: string[], cwd: string): string {
  return execFileSync(command, args, { cwd, encoding: 'utf8' }).trim();
}

function readJson<T>(file: string): T {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function writeJson(file: string, data: unknown) {
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
}

function copy(from: string, to: string) {
  if (!fs.existsSync(from)) throw new Error(`${from} not found`);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function pngsIn(dir: string): string[] {
  return fs.readdirSync(dir).filter(name => path.extname(name).toLowerCase() === '.png').sort();
}

/** The configured languages, english.json first. */
function loadLanguages(root: string): Language[] {
  const files = fs.readdirSync(path.join(root, LANGUAGES_DIR)).filter(name => name.endsWith('.json')).sort();
  files.sort((a, b) => Number(b === DEFAULT_LANGUAGE_FILE) - Number(a === DEFAULT_LANGUAGE_FILE));
  return files.map(file => ({ file, ...readJson<Omit<Language, 'file'>>(path.join(root, LANGUAGES_DIR, file)) }));
}

function logStep(n: number, text: string) {
  console.error(styleText('dim', `  ${n}/8`) + ` ${text}`);
}

// ---------------------------------------------------------------------------
// 1. Validate

function checkSettings(root: string) {
  const { report } = validate(root);
  if (report.issues.length) report.print([]);
  if (report.errorCount) {
    throw new Error('Fix the errors above before preparing the app (run npm run validate to check again)');
  }
}

// ---------------------------------------------------------------------------
// 2. Fetch the app source

/**
 * Leaves appDir as a clean checkout of ref (a branch, tag or full commit
 * hash). An existing checkout is reset rather than re-cloned so node_modules,
 * the generated native projects and Expo's .expo state survive (step 8
 * decides whether the native projects are still current); everything else,
 * including files copied in by an earlier run, is removed.
 */
function fetchApp(appDir: string, ref: string, useCache: boolean): string {
  const gitDir = path.join(appDir, '.git');
  const marker = path.join(gitDir, FETCH_MARKER);

  if (!fs.existsSync(gitDir)) {
    fs.rmSync(appDir, { recursive: true, force: true });
    fs.mkdirSync(appDir, { recursive: true });
    run('git', ['init', '--quiet'], appDir);
    run('git', ['remote', 'add', 'origin', APP_REPO], appDir);
  }

  // Reuse the commit fetched for this ref within the cache period
  const last = fs.existsSync(marker) ? readJson<{ ref: string; commit: string }>(marker) : undefined;
  let target = last?.commit;
  let note = last && `fetched ${age(marker)}; --no-cache to fetch again`;
  if (!useCache || last?.ref !== ref || !isFresh(marker)) {
    run('git', ['remote', 'set-url', 'origin', APP_REPO], appDir);
    run('git', ['fetch', '--quiet', '--depth', '1', 'origin', ref], appDir);
    target = capture('git', ['rev-parse', 'FETCH_HEAD'], appDir);
    note = 'just fetched';
    fs.writeFileSync(marker, JSON.stringify({ ref, commit: target }));
  }

  run('git', ['checkout', '--quiet', '--force', '--detach', target!], appDir);
  const keep = ['node_modules', ...NATIVE_DIRS, EXPO_STATE_DIR].flatMap(dir => ['-e', dir]);
  run('git', ['clean', '--quiet', '-fdx', ...keep], appDir);
  return `${capture('git', ['log', '-1', '--format=%h %s', 'HEAD'], appDir)} (${note})`;
}

// ---------------------------------------------------------------------------
// 3. Environment variables

/**
 * Writes .env from the app's .env.example, replacing the values that come
 * from this country's settings. Variables not listed here keep the example's
 * defaults. Fails if the app no longer has one of these variables, so a
 * renamed setting is caught here rather than silently ignored.
 */
function writeEnv(appDir: string, country: Country, alertsLanguage: Language) {
  const { forecast, region, defaults } = country;
  const values: Record<string, string> = {
    EXPO_PUBLIC_PRIMARY_API_URL: forecast.api_url,
    EXPO_PUBLIC_FALLBACK_API_URL: forecast.fallback_api_url,
    EXPO_PUBLIC_APP_USER_AGENT: forecast.user_agent,
    EXPO_PUBLIC_FORECAST_PROVIDER: forecast.provider,
    EXPO_PUBLIC_ALERTS_PROVIDER: country.alerts.provider,
    EXPO_PUBLIC_PRIMARY_ALERTS_URL: alertsLanguage.cap_feed_url,
    EXPO_PUBLIC_FALLBACK_ALERTS_URL: alertsLanguage.fallback_cap_feed_url,
    EXPO_PUBLIC_APP_ALERTS_SENDER_ID: alertsLanguage.cap_sender_id,
    EXPO_PUBLIC_APP_TIMEZONE: region.timezone,
    EXPO_PUBLIC_APP_COUNTRY_BBOX: region.bbox.join(','),
    EXPO_PUBLIC_DEFAULT_TEMPERATURE_UNIT: defaults.units.temperature,
    EXPO_PUBLIC_DEFAULT_WIND_UNIT: defaults.units.wind,
    EXPO_PUBLIC_DEFAULT_PRECIPITATION_UNIT: defaults.units.precipitation,
  };
  // The app has no on/off switch for the review prompt; a cap of 0 never asks
  if (!country.features.review_prompt) values.EXPO_PUBLIC_REVIEW_MAX_PROMPTS = '0';

  const example = fs.readFileSync(path.join(appDir, '.env.example'), 'utf8');
  const written = new Set<string>();
  const lines = example.split('\n').map(line => {
    const key = line.match(/^\s*([A-Z0-9_]+)\s*=/)?.[1];
    if (!key || !(key in values)) return line;
    written.add(key);
    return `${key}=${JSON.stringify(values[key])}`;
  });

  const missing = Object.keys(values).filter(key => !written.has(key));
  if (missing.length) {
    throw new Error(`The app's .env.example no longer has ${missing.join(', ')}; update scripts/prep/app.ts to match`);
  }
  fs.writeFileSync(path.join(appDir, '.env'), lines.join('\n'));
}

// ---------------------------------------------------------------------------
// 4. app.json

function updateAppJson(appDir: string, country: Country) {
  const file = path.join(appDir, 'app.json');
  const appJson = readJson<{ expo: Record<string, any> }>(file);
  const { expo } = appJson;
  const { app, branding } = country;

  expo.name = app.name;
  // Deep-link scheme; must be unique to the app, like its package name
  expo.scheme = app.android_package;
  expo.icon = `./${TARGETS.branding.icon}`;

  expo.ios.bundleIdentifier = app.ios_bundle_id;
  expo.android.package = app.android_package;
  expo.android.adaptiveIcon = {
    foregroundImage: `./${TARGETS.branding.adaptive_icon_foreground}`,
    backgroundColor: branding.adaptive_icon_background_colour,
  };

  // Settings › Rate this app is hidden when these are missing
  setOrDelete(expo.ios, 'appStoreUrl', app.app_store_url);
  setOrDelete(expo.android, 'playStoreUrl', app.play_store_url);

  const splash = expo.plugins.find((plugin: unknown) => Array.isArray(plugin) && plugin[0] === 'expo-splash-screen');
  if (!splash) throw new Error(`The app's app.json no longer configures expo-splash-screen; update scripts/prep/app.ts to match`);
  splash[1].image = `./${TARGETS.branding.splash_image}`;

  // The upstream EAS project and Expo account belong to the app's maintainers;
  // builds must go to the country's own project or none at all
  delete expo.owner;
  if (app.eas_project_id) {
    expo.extra = { ...expo.extra, eas: { ...expo.extra?.eas, projectId: app.eas_project_id } };
  } else if (expo.extra) {
    delete expo.extra.eas;
  }

  writeJson(file, appJson);
}

function setOrDelete(target: Record<string, unknown>, key: string, value: string) {
  if (value) target[key] = value;
  else delete target[key];
}

// ---------------------------------------------------------------------------
// 5. Assets and place data

function copyAssets(root: string, appDir: string, country: Country) {
  for (const name of pngsIn(path.join(root, 'assets/symbols'))) {
    copy(path.join(root, 'assets/symbols', name), path.join(appDir, TARGETS.symbols, name));
  }
  for (const name of pngsIn(path.join(root, 'assets/warnings'))) {
    copy(path.join(root, 'assets/warnings', name), path.join(appDir, TARGETS.warnings, name));
  }
  for (const [key, target] of Object.entries(TARGETS.branding)) {
    copy(path.join(root, country.branding[key as keyof typeof TARGETS.branding]), path.join(appDir, target));
  }

  copy(path.join(root, country.region.default_cities), path.join(appDir, TARGETS.cities));

  const geoFiles = [TARGETS.geonames.from, ...TARGETS.autocomplete.from];
  const missing = geoFiles.filter(file => !fs.existsSync(path.join(root, file)));
  if (missing.length) {
    throw new Error(`${missing.join(', ')} not found; run npm run prep -- --only geonames first`);
  }
  copy(path.join(root, TARGETS.geonames.from), path.join(appDir, TARGETS.geonames.to));
  for (const file of TARGETS.autocomplete.from) {
    copy(path.join(root, file), path.join(appDir, TARGETS.autocomplete.to, path.basename(file)));
  }
}

// ---------------------------------------------------------------------------
// 6. Languages

/**
 * Replaces the app's translations with the configured languages and
 * regenerates the LANGUAGES index. English keys the app has but this
 * repository doesn't yet are kept from the app's own english.json, so the app
 * never shows a raw key; they're listed so they can be added here.
 */
function installLanguages(appDir: string, languages: Language[]) {
  const dir = path.join(appDir, TARGETS.translations);
  const appEnglish = readJson<Record<string, string>>(path.join(dir, DEFAULT_LANGUAGE_FILE));

  for (const name of fs.readdirSync(dir).filter(name => name.endsWith('.json'))) {
    fs.rmSync(path.join(dir, name));
  }

  const entries: string[] = [];
  const imports: string[] = [];
  for (const language of languages) {
    let resources = language.translations;
    if (language.file === DEFAULT_LANGUAGE_FILE) {
      const missing = Object.keys(appEnglish).filter(key => !(key in resources));
      if (missing.length) {
        console.error(styleText('yellow', `      ⚠ ${LANGUAGES_DIR}/${DEFAULT_LANGUAGE_FILE} is missing ${missing.length} key(s) the app uses; using the app's English text for: ${missing.join(', ')}`));
        resources = { ...Object.fromEntries(missing.map(key => [key, appEnglish[key]])), ...resources };
      }
    }
    writeJson(path.join(dir, language.file), resources);

    const identifier = `${language.code.replace(/\W/g, '_')}Resources`;
    imports.push(`import ${identifier} from './${language.file}';`);
    entries.push([
      `  ${JSON.stringify(language.code)}: {`,
      `    label: ${JSON.stringify(language.native_name)},`,
      `    name: ${JSON.stringify(language.name)},`,
      `    nativeName: ${JSON.stringify(language.native_name)},`,
      `    resources: ${identifier},`,
      `  },`,
    ].join('\n'));
  }

  const index = [
    '// Generated by scripts/prep in the country repository. Do not edit; change languages/ there instead.',
    ...imports,
    '',
    'export const LANGUAGES = {',
    ...entries,
    '};',
    '',
    'export type LanguageKey = keyof typeof LANGUAGES;',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(dir, 'index.ts'), index);
}

// ---------------------------------------------------------------------------
// 7. Dependencies

/**
 * Installs exactly what the app's lockfile lists, skipping the install when
 * node_modules already matches it (unless useCache is false), then has Expo check every package against
 * the app's SDK version.
 */
function installDependencies(appDir: string, useCache: boolean) {
  const lockHash = createHash('sha256').update(fs.readFileSync(path.join(appDir, 'package-lock.json'))).digest('hex');
  const marker = path.join(appDir, INSTALL_MARKER);
  if (useCache && fs.existsSync(marker) && fs.readFileSync(marker, 'utf8') === lockHash) {
    console.error('      node_modules is up to date; --no-cache to reinstall');
  } else {
    try {
      run('npm', ['ci'], appDir);
    } catch {
      throw new Error("npm ci failed (see npm's output above). The app's dependencies don't install cleanly at this version; this needs fixing in the app repository, or use --ref to prepare an earlier version");
    }
    fs.writeFileSync(marker, lockHash);
  }

  try {
    run('npx', ['expo', 'install', '--check'], appDir, { CI: '1' });
  } catch {
    throw new Error('Expo reports packages that don\'t match the app\'s SDK version; this needs fixing in the app repository');
  }
}

// ---------------------------------------------------------------------------
// 8. Native projects

/**
 * Keeps the ios/ and android/ projects that expo run generated last time, so
 * it doesn't have to regenerate them and run pod install again, unless
 * something they're generated from has changed. That's decided with Expo's
 * own fingerprint of the app (app.json, icons, native packages and so on),
 * which is what Expo uses to tell whether a native rebuild is needed.
 */
async function checkNativeProjects(appDir: string, useCache: boolean) {
  const marker = path.join(appDir, '.git', NATIVE_MARKER);
  const present = NATIVE_DIRS.filter(dir => fs.existsSync(path.join(appDir, dir)));
  const removeNative = (reason: string) => {
    for (const dir of present) fs.rmSync(path.join(appDir, dir), { recursive: true, force: true });
    if (present.length) console.error(`      ${reason}; removed ${present.join('/ and ')}/ so expo run regenerates them`);
  };

  let fingerprint: { createFingerprintAsync: (root: string, options: object) => Promise<{ hash: string }> };
  try {
    fingerprint = require(require.resolve('@expo/fingerprint', { paths: [appDir] }));
  } catch {
    // Without it (e.g. --skip-install on a fresh checkout) there's no way to tell
    fs.rmSync(marker, { force: true });
    return removeNative("Can't check them without the app's dependencies");
  }

  // The native projects themselves are generated, so leave them out
  const { hash } = await fingerprint.createFingerprintAsync(appDir, { ignorePaths: NATIVE_DIRS.flatMap(dir => [dir, `${dir}/**`]) });
  const last = fs.existsSync(marker) ? readJson<{ hash: string }>(marker).hash : undefined;

  if (!present.length) {
    console.error('      None yet; expo run will generate them');
  } else if (!useCache) {
    removeNative('--no-cache');
  } else if (!last) {
    removeNative("No record of what they were generated from");
  } else if (hash !== last) {
    removeNative('The app or its settings changed in a way that affects them');
  } else {
    console.error(`      Unchanged; keeping ${present.join('/ and ')}/ (no pod install needed)`);
  }
  fs.writeFileSync(marker, JSON.stringify({ hash }));
}

// ---------------------------------------------------------------------------

export async function prepApp({ root, ref = DEFAULT_REF, skipInstall, validated, cache = true }: AppOptions): Promise<void> {
  const appDir = path.join(root, APP_DIR);

  if (validated) {
    logStep(1, 'Settings already validated');
  } else {
    logStep(1, 'Validating settings');
    checkSettings(root);
  }
  const country = readJson<Country>(path.join(root, 'country.json'));
  const languages = loadLanguages(root);

  logStep(2, `Fetching ${APP_REPO} (${ref}) into ${APP_DIR}`);
  const commit = fetchApp(appDir, ref, cache);
  console.error(`      at ${commit}`);

  logStep(3, `Writing .env (alert feeds from ${LANGUAGES_DIR}/${languages[0].file})`);
  writeEnv(appDir, country, languages[0]);

  logStep(4, 'Updating app.json');
  updateAppJson(appDir, country);

  logStep(5, 'Copying assets and place data');
  copyAssets(root, appDir, country);

  logStep(6, `Installing languages: ${languages.map(l => l.code).join(', ')}`);
  installLanguages(appDir, languages);

  if (skipInstall) {
    logStep(7, 'Skipping dependency install (--skip-install)');
  } else {
    logStep(7, 'Installing dependencies');
    installDependencies(appDir, cache);
  }

  logStep(8, 'Checking the native projects (ios/, android/)');
  await checkNativeProjects(appDir, cache);
}
